# -*- coding: utf-8 -*-
"""往小说 agent 记忆注入「读者友好度」写作铁律（通过 remember_skill API，不直接写 JSON）。"""
import sys
sys.path.insert(0, r"E:\神经网络")
from memagent.agent import MemoryAgent, MemoryStore, AgentConfig

store = MemoryStore(path=r"E:\神经网络\agent_memory.json")
agent = MemoryAgent(store=store, persona="novelist", cfg=AgentConfig())

rules = [
    ("写作铁律：新读者理解度是硬约束。每章首次出现的专有术语（塔纹/淬生气/锈脉/错季/骨契/残蜕/影/造血深渊/错季相/脊骨/当票/噬账兽/锁扣/断魂崖/折丹/未时/霜意/九川/魇覆/命格/当主/骨画/水漏/三魂/错季裂隙/错季城）必须配 5-15 字内嵌解释，格式：术语——解释性短语，例如『塔纹——他掌心自幼就有的九道银色裂痕』，不可假设读者记得上下文。", 0.97),
    ("写作铁律：跨章引用旧设定（前 N 章埋的伏笔、人物关系、世界观细节）时必须给读者一句轻量提示。格式：『锈脉——上次断魂崖那根贯穿他血脉的暗管』。绝不可直接说『锈脉又紧了』让读者回去翻几十章。", 0.97),
    ("写作铁律：每章结尾要能被读者在 10 秒内复述『这一章发生了什么』。写完读一遍，如果连你自己都说不出本章主角做了什么动作、遇到了什么、得到了什么信息，说明节奏或信息投放失败了。", 0.96),
    ("写作改进：本章首次出现的专有名词，在正文中（不是靠对话硬灌）用一次内嵌解释；同一个术语在一章内只解释一次，避免重复显累赘。", 0.95),
    ("写作改进：本章如果引入了一个新角色，第一次出场时给读者至少 3 个可识别标签（外貌/身份/与主角的关系）。示例：『裴枕灯——商会账房先生，沈昭典当梦境之核那晚唯一在场的人，眼下总带一点墨黑的青』。", 0.95),
    ("写作改进：对话中不得堆砌专有名词。坏写法：『他指了指锈脉，说错季相的三魂』。好写法：『他指了指锈脉——那道暗管里沉着的错季相，三魂俱在其中』。", 0.94),
    ("写作铁律：本章如果引入一个新的力量体系/境界/物品能力，必须在当章用一段不超过 6 行的内心独白或动作描写让读者『看见』它的作用，不可只给名字不给效果。示例：『淬生气——从骨髓里抽出来的暖流，每抽一次胸口就空一块，抽三次会咳血』。", 0.94),
    ("写作改进：每 5-8 章检查一次本章『新术语密度』——一个章节最多引入 3 个全新术语，超过就必须压缩到下一章或合并解释。", 0.93),
]

for rule, imp in rules:
    try:
        m = agent.remember_skill(rule, importance=imp)
        print(f"OK imp={m.importance:.2f} acc={m.access_count}  {rule[:40]}...")
    except Exception as e:
        print(f"ERR {rule[:30]}: {e}")

store.save()
print("\nsaved. total skill memories:", len([m for m in store.all() if m.kind == "skill"]))